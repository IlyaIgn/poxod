const HeroStory = {
  chapters: HERO_STORY_CHAPTERS,

  totalChapters() {
    return HERO_STORY_CHAPTERS.length;
  },

  loadProgress() {
    try {
      const raw = localStorage.getItem(HERO_STORY_STORAGE_KEY);
      if (!raw) return 0;
      const n = parseInt(JSON.parse(raw).unlocked, 10);
      return Number.isFinite(n) ? Phaser.Math.Clamp(n, 0, this.totalChapters()) : 0;
    } catch {
      return 0;
    }
  },

  saveProgress(unlocked) {
    try {
      localStorage.setItem(
        HERO_STORY_STORAGE_KEY,
        JSON.stringify({ unlocked: Phaser.Math.Clamp(unlocked, 0, this.totalChapters()) }),
      );
    } catch (err) {
      console.warn('[HeroStory] Не удалось сохранить прогресс', err);
    }
  },

  getUnlockedCount() {
    return GameState.storyUnlocked || 0;
  },

  syncFromStorage() {
    const legacy = this.loadProgress();
    if (legacy > (GameState.storyUnlocked || 0)) {
      GameState.storyUnlocked = legacy;
      if (typeof SaveManager !== 'undefined') {
        SaveManager.scheduleSave();
      }
    }
  },

  /** Открыть следующую главу после победы над боссом. @returns {number|null} индекс главы 0..n-1 */
  unlockNextChapter() {
    const current = GameState.storyUnlocked || 0;
    if (current >= this.totalChapters()) return null;
    const next = current + 1;
    GameState.storyUnlocked = next;
    this.saveProgress(next);
    if (typeof SaveManager !== 'undefined') {
      SaveManager.scheduleSave();
    }
    return next - 1;
  },

  getChapter(index) {
    return HERO_STORY_CHAPTERS[index] || null;
  },

  chapterProgressLabel() {
    const n = this.getUnlockedCount();
    return `${n}/${this.totalChapters()}`;
  },

  /**
   * Читалка главы (оверлей на сцене).
   * @param {Phaser.Scene} scene
   * @param {number} chapterIndex
   * @param {{ onClose?: Function, auto?: boolean }} options
   */
  openReader(scene, chapterIndex, options = {}) {
    const chapter = this.getChapter(chapterIndex);
    if (!chapter || scene.storyReader) return;

    const { width, height } = scene.scale;
    const cx = width / 2;
    const cy = height / 2;
    const pages = chapter.pages || [];
    let page = 0;
    const panelW = Math.min(640, Math.round(width * 0.82));
    const panelH = Math.min(440, Math.round(height * 0.78));
    const wrapW = Math.min(560, panelW - 80);

    const overlay = scene.add.rectangle(cx, cy, width, height, 0x000000, 0.82)
      .setInteractive()
      .setDepth(5000);
    const panel = scene.add.rectangle(cx, cy, panelW, panelH, 0x1a2332, 0.98)
      .setStrokeStyle(2, 0x5d6d7e)
      .setDepth(5001);
    const titleY = cy - panelH / 2 + 42;
    const subtitleY = titleY + 30;
    const bodyY = cy - 8;
    const controlsY = cy + panelH / 2 - 42;

    const title = scene.add.text(cx, titleY, chapter.title, {
      fontSize: scaleFontSize(scene, 22),
      color: '#f0e6d3',
      fontStyle: 'bold',
      align: 'center',
      wordWrap: { width: wrapW },
    }).setOrigin(0.5).setDepth(5002);
    const subtitle = scene.add.text(cx, subtitleY, chapter.subtitle, {
      fontSize: scaleFontSize(scene, 13),
      color: '#8b9cb3',
      align: 'center',
    }).setOrigin(0.5).setDepth(5002);

    const body = scene.add.text(cx, bodyY, '', {
      fontSize: scaleFontSize(scene, 15),
      color: '#d5dbdb',
      align: 'center',
      wordWrap: { width: wrapW },
      lineSpacing: 8,
    }).setOrigin(0.5).setDepth(5002);

    const pageHint = scene.add.text(cx, controlsY - 30, '', {
      fontSize: scaleFontSize(scene, 12),
      color: '#7f8c8d',
    }).setOrigin(0.5).setDepth(5002);

    const btnStyle = {
      fontSize: scaleFontSize(scene, 15),
      color: '#ecf0f1',
      backgroundColor: '#34495e',
      padding: { x: 14, y: 8 },
    };

    const btnPrev = scene.add.text(cx - 120, controlsY, '← Назад', btnStyle)
      .setOrigin(0.5).setDepth(5003).setInteractive({ useHandCursor: true });
    const btnNext = scene.add.text(cx + 120, controlsY, 'Далее →', btnStyle)
      .setOrigin(0.5).setDepth(5003).setInteractive({ useHandCursor: true });
    const btnClose = scene.add.text(cx, controlsY, 'Закрыть', {
      ...btnStyle,
      backgroundColor: '#7b241c',
    }).setOrigin(0.5).setDepth(5003).setInteractive({ useHandCursor: true });

    const refreshPage = () => {
      body.setText(pages[page] || '');
      pageHint.setText(`Страница ${page + 1} из ${pages.length}`);
      btnPrev.setAlpha(page > 0 ? 1 : 0.35);
      btnNext.setText(page < pages.length - 1 ? 'Далее →' : 'Закрыть');
    };

    const close = () => {
      if (!scene.storyReader?.active) return;
      scene.storyReader.destroy();
      scene.storyReader = null;
      options.onClose?.();
    };

    btnPrev.on('pointerdown', () => {
      if (page > 0) {
        page -= 1;
        refreshPage();
      }
    });
    btnNext.on('pointerdown', () => {
      if (page < pages.length - 1) {
        page += 1;
        refreshPage();
      } else {
        close();
      }
    });
    btnClose.on('pointerdown', close);
    overlay.on('pointerdown', () => {});

    scene.storyReader = scene.add.container(0, 0, [
      overlay, panel, title, subtitle, body, pageHint, btnPrev, btnNext, btnClose,
    ]).setDepth(5000);

    refreshPage();

    if (options.auto) {
      scene.tweens.add({
        targets: scene.storyReader,
        alpha: { from: 0, to: 1 },
        duration: 280,
      });
      scene.storyReader.alpha = 0;
    }
  },

  /** Список открытых глав */
  openChronicles(scene) {
    const unlocked = this.getUnlockedCount();
    if (unlocked <= 0) {
      scene.showCenterAlert?.(GameConfig.text.story.empty);
      return;
    }

    const { width, height } = scene.scale;
    const cx = width / 2;
    const cy = height / 2;

    const overlay = scene.add.rectangle(cx, cy, width, height, 0x000000, 0.75)
      .setInteractive()
      .setDepth(4900);
    const panelH = Math.min(Math.round(height * 0.72), 120 + unlocked * 32);
    const panelW = Math.min(440, Math.round(width * 0.55));
    const panel = scene.add.rectangle(cx, cy, panelW, panelH, 0x1a2332, 0.98)
      .setStrokeStyle(2, 0x5d6d7e)
      .setDepth(4901);
    const header = scene.add.text(cx, cy - panelH / 2 + 28, GameConfig.text.story.listTitle, {
      fontSize: scaleFontSize(scene, 18),
      color: '#f0e6d3',
      fontStyle: 'bold',
    }).setOrigin(0.5).setDepth(4902);

    const items = [];
    const listTop = cy - panelH / 2 + 58;
    for (let i = 0; i < unlocked; i++) {
      const ch = HERO_STORY_CHAPTERS[i];
      const y = listTop + i * 32;
      const row = scene.add.text(cx, y, `${ch.id}. ${ch.title}`, {
        fontSize: scaleFontSize(scene, 13),
        color: '#7bed9f',
        fontStyle: 'bold',
      }).setOrigin(0.5).setDepth(4903).setInteractive({ useHandCursor: true });
      row.on('pointerdown', () => {
        scene.chroniclesMenu?.destroy();
        scene.chroniclesMenu = null;
        this.openReader(scene, i, { onClose: () => this.openChronicles(scene) });
      });
      row.on('pointerover', () => row.setColor('#f1c40f'));
      row.on('pointerout', () => row.setColor('#7bed9f'));
      items.push(row);
    }

    const hint = scene.add.text(cx, cy + panelH / 2 - 52, GameConfig.format(GameConfig.text.story.listProgress, {
      unlocked,
      total: this.totalChapters(),
    }), {
      fontSize: scaleFontSize(scene, 12),
      color: '#95a5a6',
    }).setOrigin(0.5).setDepth(4902);

    const btnClose = scene.add.text(cx, cy + panelH / 2 - 22, 'Закрыть', {
      fontSize: scaleFontSize(scene, 15),
      color: '#ecf0f1',
      backgroundColor: '#34495e',
      padding: { x: 16, y: 8 },
    }).setOrigin(0.5).setDepth(4903).setInteractive({ useHandCursor: true });

    btnClose.on('pointerdown', () => {
      scene.chroniclesMenu?.destroy();
      scene.chroniclesMenu = null;
    });

    scene.chroniclesMenu = scene.add.container(0, 0, [overlay, panel, header, hint, btnClose, ...items])
      .setDepth(4900);
  },
};
